export type TranslationKey = keyof typeof translations.en;

const I18nContext = createContext<I18nContextValue | null>(null);

const interpolate = (template: string, vars?: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_match, key) => String(vars?.[key] ?? ""));

const detectLocale = (): SupportedLocale => {
  if (typeof window === "undefined") {
    return "en";
  }

  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "mn" || stored === "ja") {
    return stored;
  }

  const languages = [...(window.navigator.languages || []), window.navigator.language].filter(Boolean);
  if (languages.some((value) => value.toLowerCase().startsWith("mn"))) {
    return "mn";
  }
  if (languages.some((value) => value.toLowerCase().startsWith("ja"))) {
    return "ja";
  }
  if (languages.some((value) => value.toLowerCase().startsWith("en"))) {
    return "en";
  }

  const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone;
  if (timeZone.includes("Ulaanbaatar") || timeZone.includes("Ulan_Bator")) {
    return "mn";
  }
  if (timeZone.includes("Tokyo")) {
    return "ja";
  }

  return "en";
};

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<SupportedLocale>(() => detectLocale());

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale: setLocaleState,
      t: (key, vars) => interpolate(translations[locale][key] || translations.en[key], vars),
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside LanguageProvider");
  }
  return context;
}

export const getStaticTranslation = (locale: SupportedLocale, key: TranslationKey, vars?: Record<string, string | number>) =>
  interpolate(translations[locale][key] || translations.en[key], vars);
